#!/usr/bin/env node
// Generates src/types.generated.ts and src/truckLimits.generated.ts from contracts/openapi.json (a snapshot of the backend's /api/openapi.json).
//   node scripts/gen-types.mjs            write the file
//   node scripts/gen-types.mjs --check    exit 1 when the committed file differs (CI drift test)
// Refresh the snapshot from a running backend: curl -s http://localhost:8001/api/openapi.json > contracts/openapi.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "contracts/openapi.json");
const out = resolve(root, "src/types.generated.ts");
const header = "// GENERATED by scripts/gen-types.mjs from contracts/openapi.json. Do not edit; regenerate.\n";
const ast = await openapiTS(new URL(`file://${src}`), { alphabetize: true });
const text = header + astToString(ast);

// The truck's size limits, from the same schema the server validates with: the app's forms read these, so a
// limit changed on the server shows up here (and in the drift test) instead of in two hand-kept copies.
const limitsOut = resolve(root, "src/truckLimits.generated.ts");
const truck = JSON.parse(readFileSync(src, "utf8")).components.schemas.TruckProfile.properties;
const range = (k) => `[${truck[k].minimum}, ${truck[k].maximum}]`;
const limitsText =
  header +
  "export const TRUCK_LIMITS = {\n" +
  `  height_in: ${range("height_in")},\n  trailer_ft: ${range("trailer_ft")},\n  weight_lb: ${range("weight_lb")},\n` +
  "} as const;\n";

if (process.argv.includes("--check")) {
  for (const [file, want, name] of [[out, text, "types.generated.ts"], [limitsOut, limitsText, "truckLimits.generated.ts"]]) {
    if (readFileSync(file, "utf8") !== want) {
      console.error(`src/${name} is out of date with contracts/openapi.json; run: node scripts/gen-types.mjs`);
      process.exit(1);
    }
  }
  console.log("generated files match the contract");
} else {
  writeFileSync(out, text);
  writeFileSync(limitsOut, limitsText);
  console.log(`wrote ${out} and ${limitsOut}`);
}
